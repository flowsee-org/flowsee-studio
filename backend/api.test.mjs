import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
process.env.STUDIO_DATA_DIR = mkdtempSync(join(tmpdir(), 'studio-test-'));
process.env.STUDIO_ADMIN_EMAIL = 'owner@example.test';
process.env.STUDIO_ADMIN_PASSWORD = 'test-password-12345';
const { server } = await import('./server.mjs');
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const base = '/api/apps/studio';
async function call(path, method = 'GET', body, token) {
  const res = await fetch(origin + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  return { status: res.status, data: await res.json() };
}
after(async () => { await new Promise(resolve => server.close(resolve)); rmSync(process.env.STUDIO_DATA_DIR, { recursive: true, force: true }); });
test('local authentication, permissions, persistence, uploads and logout', async () => {
  assert.equal((await call(`${base}/entities/Task`)).status, 401);
  assert.equal((await call(`${base}/entities/Task`, 'GET', undefined, 'a.b.c')).status, 401);
  const login = await call(`${base}/auth/login`, 'POST', { email: process.env.STUDIO_ADMIN_EMAIL, password: process.env.STUDIO_ADMIN_PASSWORD });
  assert.equal(login.status, 200);
  const admin = login.data.access_token;
  const invitation = await call(`${base}/runtime/users/invite-user`, 'POST', { user_email: 'staff@example.test', role: 'user', initial_password: 'staff-test-password' }, admin);
  assert.equal(invitation.status, 200);
  const staff = (await call(`${base}/auth/login`, 'POST', { email: 'staff@example.test', password: 'staff-test-password' })).data.access_token;
  assert.equal((await call(`${base}/entities/User/${invitation.data.user.id}`, 'PUT', { role: 'superadmin' }, staff)).status, 403);
  assert.equal((await call(`${base}/entities/User`, 'POST', { role: 'superadmin' }, staff)).status, 403);
  assert.equal((await call(`${base}/entities/Salary`, 'GET', undefined, staff)).status, 403);
  const task = await call(`${base}/entities/Task`, 'POST', { title: 'Local test' }, admin);
  assert.equal(task.status, 200);
  assert.equal((await call(`${base}/entities/Task/${task.data.id}`, 'PUT', { title: 'Updated' }, admin)).status, 200);
  assert.equal((await call(`${base}/entities/Task?q=${encodeURIComponent(JSON.stringify({ title: 'Updated' }))}`, 'GET', undefined, admin)).data.length, 1);
  const disk = JSON.parse(readFileSync(join(process.env.STUDIO_DATA_DIR, 'db.json')));
  assert.equal(disk.entities.Task[0].title, 'Updated');
  assert.equal(disk.users.length, 2);
  assert.equal((await call(`${base}/entities/Task/${task.data.id}`, 'DELETE', undefined, admin)).status, 200);
  assert.equal((await call(`${base}/entities/Task/${task.data.id}/restore`, 'POST', {}, staff)).status, 403);
  assert.equal((await call(`${base}/entities/Task/${task.data.id}/restore`, 'POST', {}, admin)).status, 200);
  const form = new FormData(); form.append('file', new Blob(['hello'], { type: 'text/plain' }), 'test.txt');
  const upload = await fetch(origin + `${base}/integration-endpoints/Core/UploadFile`, { method: 'POST', headers: { Authorization: `Bearer ${admin}` }, body: form });
  assert.equal(upload.status, 200);
  assert.match((await upload.json()).file_url, /^data:text\/plain;base64,/);
  const backup = await call(`${base}/backup`, 'GET', undefined, admin);
  assert.equal(backup.status, 200);
  assert.equal(backup.data.secret, undefined);
  assert.equal(backup.data.users[0].password_hash, undefined);
  assert.equal(backup.data.entities.Task.some((item) => item.title === 'Updated'), true);
  assert.equal(Object.hasOwn(backup.data.entities, 'User'), false);
  const backupResponse = await fetch(origin + `${base}/backup`, { headers: { Authorization: ['Bearer ', admin].join('') } });
  assert.match(backupResponse.headers.get('content-disposition'), /attachment; filename="flowsee-backup-\d{4}-\d{2}-\d{2}\.json"/);
  const backupFile = new FormData();
  backupFile.append('file', new Blob([await backupResponse.text()], { type: 'application/json' }), 'flowsee-backup.json');
  assert.equal((await fetch(origin + `${base}/restore`, { method: 'POST', headers: { Authorization: ['Bearer ', admin].join('') }, body: backupFile })).status, 200);
  const restore = new FormData(); restore.append('file', new Blob([JSON.stringify({ entities: { Project: [{ id: 'imported', name: 'Import' }] } })]), 'backup.json');
  assert.equal((await fetch(origin + `${base}/restore`, { method: 'POST', headers: { Authorization: `Bearer ${admin}` }, body: restore })).status, 200);
  assert.equal((await call(`${base}/entities/Project/imported`, 'GET', undefined, admin)).data.name, 'Import');
  assert.equal((await call(`${base}/auth/register`, 'POST', { email: 'blocked@example.test', password: 'password12345' })).status, 403);
  await call(`${base}/auth/reset-password-request`, 'POST', { email: 'staff@example.test' });
  const inbox = readFileSync(join(process.env.STUDIO_DATA_DIR, 'otp-inbox.log'), 'utf8');
  const resetToken = inbox.match(/token=([a-f0-9]+)/)[1];
  assert.equal((await call(`${base}/auth/reset-password`, 'POST', { reset_token: resetToken, new_password: 'changed-password123' })).status, 200);
  assert.equal((await call(`${base}/entities/User/me`, 'GET', undefined, staff)).status, 401);
  assert.equal((await call(`${base}/auth/reset-password`, 'POST', { reset_token: resetToken, new_password: 'another-password123' })).status, 400);
  assert.equal((await call('/api/apps/auth/login')).status, 404);
  assert.equal((await call('/api/apps/auth/logout', 'POST', {}, admin)).status, 200);
  assert.equal((await call(`${base}/entities/User/me`, 'GET', undefined, admin)).status, 401);
});
