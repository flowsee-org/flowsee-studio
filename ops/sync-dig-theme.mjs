import fs from 'node:fs';
import postcss from 'postcss';

// Keep Dig's generated source untouched. Scope its tokens to new Dig surfaces
// while the existing application uses Tailwind 3's HSL channel variables.
const sources = ['src/app/dig-theme.css', 'src/app/brand.css'];
const output = postcss.root();
for (const source of sources) {
  const css = postcss.parse(fs.readFileSync(source, 'utf8'));
  css.nodes.filter(node => node.type === 'rule' && (node.selector === ':root' || node.selector === '.dark')).forEach(rule => {
    const copy = rule.clone();
    copy.selector = rule.selector === ':root' ? '.dig-ui' : '.dark .dig-ui';
    output.append(copy);
  });
}
output.append(postcss.parse('.dig-ui{--font-anchor:Vazirmatn,ui-sans-serif,system-ui,sans-serif;--primary-foreground:var(--dig-black)}'));
fs.writeFileSync('src/app/dig-runtime.css', '/* Generated by npm run dig:sync. Do not edit. */\n' + output.toString());
